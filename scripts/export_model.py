"""Write a TFLite model into the firmware as a C array (firmware/common/model_data.{h,cc}).

This model is the board's built-in model. board_probe.py can also upload any other model
over serial at run time, so you only need to re-export + reflash for standalone demos.

Usage:
  python scripts/export_model.py --tflite models/foo.tflite
  python scripts/export_model.py --machine machine-1-1 --seed 0 --variant int8-pc   # builds/caches in models/
"""
import argparse
import sys
import zlib
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "common"


def quant_params(tfl: bytes):
    import tensorflow as tf
    it = tf.lite.Interpreter(model_content=tfl)
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    assert i["dtype"] == np.int8 and o["dtype"] == np.int8, "model must have int8 input/output"
    q = lambda d: (float(d["quantization"][0]), int(d["quantization"][1]))  # noqa: E731
    return q(i), q(o), [int(d) for d in i["shape"]], [int(d) for d in o["shape"]]


def write(tfl: bytes, tag: str, out_dir: Path = OUT):
    (s_in, z_in), (s_out, z_out), ish, osh = quant_params(tfl)
    crc = zlib.crc32(tfl)
    rows = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in tfl[i:i + 16]) for i in range(0, len(tfl), 16))
    head = (f"// Generated by scripts/export_model.py from {tag}. Do not edit.\n"
            f"// input {ish} scale {s_in!r} zero_point {z_in}; output {osh} scale {s_out!r} "
            f"zero_point {z_out}; {len(tfl)} bytes, crc32 0x{crc:08x}\n")
    (out_dir / "model_data.h").write_text(
        head + "#pragma once\n\n"
        "extern const unsigned char coda_model_data[];\n"
        "extern const unsigned int coda_model_len;\n"
        "extern const char coda_model_tag[];\n"
        f"#define CODA_MODEL_CRC32 0x{crc:08x}u\n"
        f"#define CODA_MODEL_IN_SCALE {s_in!r}f\n#define CODA_MODEL_IN_ZERO_POINT {z_in}\n"
        f"#define CODA_MODEL_OUT_SCALE {s_out!r}f\n#define CODA_MODEL_OUT_ZERO_POINT {z_out}\n")
    (out_dir / "model_data.cc").write_text(
        head + '#include "model_data.h"\n\n'
        f'const char coda_model_tag[] = "{tag}";\n'
        f"const unsigned int coda_model_len = {len(tfl)};\n"
        f"alignas(16) const unsigned char coda_model_data[] = {{\n{rows}\n}};\n")
    print(f"wrote {out_dir}/model_data.{{h,cc}}: {tag}, {len(tfl)} bytes, crc32 0x{crc:08x}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tflite", help="existing .tflite file")
    ap.add_argument("--machine", default="machine-1-1")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--variant", default="int8-pc", choices=["int8-pc", "int8-pt", "w4a8"])
    ap.add_argument("--protocol", default="blocks", choices=["blocks", "time"])
    ap.add_argument("--block", type=int, default=128)
    ap.add_argument("--epochs", type=int, default=20)
    a = ap.parse_args()
    if a.tflite:
        p = Path(a.tflite)
        write(p.read_bytes(), p.stem)
    else:
        sys.path.insert(0, str(ROOT / "scripts"))
        import coda_models
        b = coda_models.get(a.machine, a.seed, a.protocol, a.block, a.epochs)
        write(b.tflite[a.variant], f"{b.tag}_{a.variant}")


if __name__ == "__main__":
    main()
